from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "probe" / "docs"
PAD_TO = 13200


def table(rows: list[tuple[str, str, str, str]]) -> str:
    lines = [
        "| Наименование | Обозначение | Формат | Обязательность |",
        "| --- | --- | --- | --- |",
    ]
    for name, title, fmt, required in rows:
        lines.append(f"| {name} | {title} | {fmt} | {required} |")
    return "\n".join(lines)


def pad(text: str, topic: str) -> str:
    number = 1
    while len(text) < PAD_TO:
        text += (
            f"\n\nПравило {number} для «{topic}». Сотрудник сверяет пакет с журналом смены, "
            "фиксирует расхождение отдельной строкой и не начинает новый вызов. "
            "Повтор проверки в следующем окне остаётся тем же методом. "
            "Соседнее поле не подменяет значение, список глаголов не порождает адрес."
        )
        number += 1
    return text


def preamble(title: str, version: str, purpose: str) -> str:
    return "\n".join(
        [
            f"# {title}",
            "",
            f"v {version}",
            "",
            purpose,
            "",
            "## История изменений",
            "",
            "| Версия | Дата |",
            "| --- | --- |",
            "| 0.1 | 01.02.2020 |",
            "",
        ]
    )


def method(heading: str, verb: str, url: str, summary: str, topic: str, tail: str) -> str:
    head = "\n".join(
        [
            f"## {heading}",
            "",
            summary,
            "",
            f"{verb} {url}",
            "",
            "Параметры этого вызова и коды ответов приведены в конце метода, после правил.",
            "",
        ]
    )
    return pad(head, topic) + "\n\n" + tail.strip() + "\n"


def write(name: str, text: str) -> None:
    path = DOCS / name
    path.write_text(text.strip() + "\n", encoding="utf-8")
    print(name, len(text))


